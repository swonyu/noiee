// Static integration checks only. No backend, Keychain, browser or installed app.
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const read=name=>readFileSync(new URL('../source/'+name,import.meta.url),'utf8');
const agent=read('agent.mjs'),native=read('Tools.swift'),app=read('App.swift'),ui=read('PrivateAccountsUI.swift');
const statement=agent.split('\n').find(line=>line.startsWith("AGENT_TOOLS.push(tool('private_accounts'"));
const catalog=[];
vm.runInNewContext(statement,{AGENT_TOOLS:catalog,tool:(name,description,parameters)=>({name,description,parameters})});
const tool=JSON.parse(JSON.stringify(catalog[0]));
assert.equal(tool.name,'private_accounts');
assert.deepEqual(tool.parameters.properties.action.enum,['status','github_repository','github_issues','gmail_messages','gmail_message_metadata','drive_file_metadata','drive_file_text']);
assert.deepEqual(Object.keys(tool.parameters.properties),['action','repository','page','query','pageToken','id']);
assert.equal(tool.parameters.additionalProperties,false);
assert.match(tool.description,/Drive IDs must come from native Google Picker/);
assert.match(native,/if name=="private_accounts" \{try await beforeEffect\?\(\);try require\(expected\);let result=try await performPrivateAccounts\(arguments,expected:expected\);try require\(expected\);return result\}/);
assert.match(app,/@objc private func showPrivateAccounts\(\) \{tools\.showPrivateAccounts\(\)\}/);
assert.match(app,/appMenu\.addItem\(withTitle:"Private Accounts…",action:#selector\(showPrivateAccounts\)/);
assert.match(native,/privateAccountsUI\.cancel\(\)/);
assert.doesNotMatch(native,/case "(?:privateAccountsConnect|githubConnect|privateAccountsConfigure)"/);
assert.doesNotMatch(ui,/ToolAccessMode|skipsConfirmation|WKScriptMessage|evaluateJavaScript/);
assert.match(ui,/try await self\.review\("Authorize this GitHub App\?/);
assert.match(ui,/try await self\.review\("Allow these GitHub reads\?/);
assert.match(ui,/Tokens stay in this Mac's Keychain/);
assert.match(ui,/grant survives app restart/);
const gmailUI=read('GmailAccountUI.swift'),gmail=read('GmailAccount.swift');
assert.doesNotMatch(gmailUI,/ToolAccessMode|skipsConfirmation|WKScriptMessage|evaluateJavaScript/);
assert.match(gmailUI,/try await self\.review\("Connect the Google account you choose\?/);
assert.match(gmailUI,/This grant does not authorize any cloud model\/provider or Coding chat/);
assert.match(gmailUI,/Revoke this Google project's access\?/);
assert.match(gmailUI,/all its OAuth clients/);
assert.match(gmail,/destination=="local-agent-conversation-v1"/);
assert.match(native,/PrivateAccountsDispatch\.collect\(/);
assert.match(native,/check:\{try self\.require\(expected\)\}/);
assert.match(native,/try await self\.gmailAccount\.perform\(input\)/);
assert.match(ui,/gmailUI\.cancel\(\)/);
assert.doesNotMatch(native,/case "(?:gmailConnect|gmailRevoke|gmailConfigure)"/);
const driveUI=read('DriveAccountUI.swift'),drive=read('DriveAccount.swift'),driveOAuth=read('DriveOAuth.swift');
assert.doesNotMatch(driveUI,/ToolAccessMode|skipsConfirmation|WKScriptMessage|evaluateJavaScript/);
assert.match(driveUI,/try await self\.review\("Choose Drive files for local Agent\?/);
assert.match(driveUI,/Google grants access including write capability/);
assert.match(driveUI,/No cloud model or Coding destination is authorized/);
assert.match(drive,/destination==DrivePolicy\.destination/);
assert.match(driveOAuth,/name:"trigger_onepick",value:"true"/);
assert.match(native,/try await self\.driveAccount\.perform\(input\)/);
assert.match(ui,/driveUI\.cancel\(\)/);
assert.doesNotMatch(native,/case "(?:driveConnect|driveRevoke|driveConfigure|drivePick)"/);
console.log('PASS: Gmail/Drive/GitHub read-only schema, native-only controls, exact local destination, Picker/write-capability disclosure and aggregate Stop routing. Static integration test only.');
