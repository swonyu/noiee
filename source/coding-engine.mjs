// One total budget bounds nesting, arrays, and strings; raw reasoning never leaves the engine.
function bounded(value, limit=24000) {
  let remaining=limit, truncated=false;
  function visit(v, depth=0) {
    if(remaining<=0||depth>12){truncated=true;return '[truncated]';}
    if(typeof v==='string'){const n=Math.min(v.length,remaining);remaining-=n;truncated ||= n<v.length;return v.slice(0,n);}
    if(v===null||typeof v!=='object'){remaining-=16;return v;}
    if(Array.isArray(v)){const out=[];for(const entry of v){if(remaining<=0){truncated=true;break;}out.push(visit(entry,depth+1));}return out;}
    if((v.type==='image'||v.type==='localImage')&&('url' in v||'path' in v))v=imageProjection(v);
    const out={};
    for(const [key,entry] of Object.entries(v)){
      if(['encrypted_content','encryptedContent','raw_content','rawContent'].includes(key))continue;
      if(v.type==='reasoning'&& !['id','type','summary'].includes(key))continue;
      if(remaining<=0){truncated=true;break;} remaining-=key.length;out[key]=visit(entry,depth+1);
    }
    return out;
  }
  return {value:visit(value),truncated};
}

